#!/usr/bin/env python3
"""Generate the Pascal PCI device table and INF model lines from pci.ids.

Usage: gen_pascal_ids.py [--check] [pci.ids]

Writes src_driver/nvx_pascal_ids.h, dist_full/nvx.inf (x64) and
dist32/nvx.inf (x86).  Only named NV130-family (GP100..GP108) entries
are taken; unnamed engineering IDs are skipped.  With --check the generated
header is compared with the committed one instead of being rewritten.
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
HEADER = HERE.parent / "nvx_pascal_ids.h"
ROOT = HERE.parent.parent
INF_DATE = "11/17/2026"  # bump together with NVX_DRIVER_VERSION
ENTRY = re.compile(r"^\t([0-9a-f]{4})  (GP10[024678][A-Z]*) \[(.+)\]$")


def parse(path):
    rows, in_nvidia = [], False
    for line in pathlib.Path(path).read_text(errors="replace").splitlines():
        if line.startswith("10de "):
            in_nvidia = True
            continue
        if in_nvidia and re.match(r"^[0-9a-f]{4} ", line):
            break
        if not in_nvidia or line.startswith("\t\t"):
            continue
        m = ENTRY.match(line)
        if m:
            dev, chip, name = m.groups()
            rows.append((int(dev, 16), chip, name))
    return sorted(rows)


def header(rows):
    out = [
        "/* Generated by tools/gen_pascal_ids.py from pci.ids; do not edit. */",
        "#ifndef NVX_PASCAL_IDS_H",
        "#define NVX_PASCAL_IDS_H",
        "#include <stdint.h>",
        "static const struct { uint16_t device; const char *name; } g_NvxPascalIds[] = {",
    ]
    for dev, chip, name in rows:
        out.append('    { 0x%04x, "NVIDIA %s (%s)" },' % (dev, name, chip))
    out += ["};", "#endif", ""]
    return "\n".join(out)


INF_TEMPLATE = """;
; NVX Pascal display + miniport driver installation file
; Target: {target}
; Chipsets: NV130 family (GP100..GP108). Generated by
; src_driver/tools/gen_pascal_ids.py; do not edit by hand.
;

[Version]
Signature   = "$CHICAGO$"
Provider    = %NVX%
ClassGUID   = {{4D36E968-E325-11CE-BFC1-08002BE10318}}
Class       = Display
DriverVer   = {date}, {version}

[DestinationDirs]
DefaultDestDir      = 11
nvx.Miniport        = 12
nvx.Display         = 11

[Manufacturer]
%NVX% = NVX.Mfg{decoration}

[NVX.Mfg{section}]
{models}

[nvx_Inst]
CopyFiles = nvx.Miniport, nvx.Display

[nvx_Inst.Services]
AddService = nvxmp, 0x00000002, nvxmp_Service_Inst, nvxmp_EventLog_Inst

[nvxmp_Service_Inst]
ServiceType    = 1                  ; SERVICE_KERNEL_DRIVER
StartType      = 1                  ; SERVICE_SYSTEM_START
ErrorControl   = 0                  ; SERVICE_ERROR_IGNORE
LoadOrderGroup = Video
ServiceBinary  = %12%\\nvxmp.sys
AddReg         = nvxmp_Service_AddReg

; Pascal cards are multi-function (display + HDMI audio).
[nvxmp_Service_AddReg]
HKR,, MultiFunctionSupported, 0x00010001, 1

[nvxmp_EventLog_Inst]
AddReg = nvxmp_EventLog_AddReg

[nvxmp_EventLog_AddReg]
HKR,,EventMessageFile,0x00020000,"%SystemRoot%\\System32\\IoLogMsg.dll;%12%\\nvxmp.sys"
HKR,,TypesSupported,0x00010001,7

[nvx_Inst.SoftwareSettings]
AddReg = nvx_SoftwareSettings_AddReg

[nvx_SoftwareSettings_AddReg]
HKR,, InstalledDisplayDrivers,     0x00010000, "nvxdisp"
HKR,, VgaCompatible,               0x00010001, 0
HKR,, MultiFunctionSupported,      0x00010001, 1

[nvx.Miniport]
nvxmp.sys

[nvx.Display]
nvxdisp.dll

[SourceDisksNames]
1 = %DiskId%,,,""

[SourceDisksFiles]
nvxmp.sys  = 1
nvxdisp.dll = 1

[Strings]
NVX                 = "NVX community port (nouveau-based XDDM)"
DiskId              = "NVX Pascal XDDM installation disk"
{strings}
"""


def inf(rows, target, section, date, version):
    models = "\n".join("%%NVX_%04X%% = nvx_Inst, PCI\\VEN_10DE&DEV_%04X" % (d, d) for d, _, _ in rows)
    strings = "\n".join('NVX_%04X = "NVIDIA %s (%s, NVX XDDM)"' % (d, n, c) for d, c, n in rows)
    return INF_TEMPLATE.format(target=target, section=section,
                               decoration=", NTamd64" if section else "",
                               models=models, strings=strings, date=date, version=version)


def driver_version():
    text = (HERE.parent / "nvxmp.c").read_text()
    return re.search(r'#define NVX_DRIVER_VERSION "([0-9.]+)"', text).group(1)


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    rows = parse(args[0] if args else "/usr/share/misc/pci.ids")
    if not any(d == 0x1B81 for d, _, _ in rows):
        sys.exit("pci.ids has no 10de:1b81 (GTX 1070); refusing to generate")
    text = header(rows)
    if check:
        if HEADER.read_text() != text:
            sys.exit("nvx_pascal_ids.h is stale; rerun tools/gen_pascal_ids.py")
        print("nvx_pascal_ids.h matches pci.ids (%d devices)" % len(rows))
        return
    HEADER.write_text(text)
    version = driver_version()
    (ROOT / "dist_full" / "nvx.inf").write_text(
        inf(rows, "Windows XP Professional x64 Edition / Server 2003 x64 (NT 5.2)",
            ".NTamd64", INF_DATE, version))
    (ROOT / "dist32" / "nvx.inf").write_text(
        inf(rows, "Windows XP x86 (NT 5.1)", "", INF_DATE, version))
    print("wrote %d Pascal devices" % len(rows))


if __name__ == "__main__":
    main()
